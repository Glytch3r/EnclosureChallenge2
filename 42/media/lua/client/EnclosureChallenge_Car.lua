EnclosureChallenge = EnclosureChallenge or {}

function EnclosureChallenge.getVehicleSeat(pl, vehicle)
    vehicle = vehicle or (pl and pl:getVehicle())
    if not vehicle or not pl then return -1 end
    return vehicle:getSeat(pl) or -1
end

function EnclosureChallenge.reboundMoveVehicle(vehicle, x, y)
    if not vehicle or not x or not y then return false end
    local cell = vehicle:getCell()
    local square = cell and cell:getGridSquare(math.floor(x), math.floor(y), vehicle:getZ()) or nil
    if not square then return false end
    local otherVehicle = square:getVehicleContainer()
    if otherVehicle and otherVehicle ~= vehicle then return false end
    if IsoFlagType and (square:has(IsoFlagType.collideN) or square:has(IsoFlagType.collideW)) then return false end
    local transform = BaseVehicle.allocTransform()
    vehicle:getWorldTransform(transform)
    local origin = transform:getOrigin()
    origin:set(origin:x() + (x - vehicle:getX()), origin:y(), origin:z() + (y - vehicle:getY()))
    vehicle:setWorldTransform(transform)
    BaseVehicle.releaseTransform(transform)
    pcall(vehicle.update, vehicle)
    pcall(vehicle.updateControls, vehicle)
    pcall(vehicle.updateBulletStats, vehicle)
    pcall(vehicle.updatePhysics, vehicle)
    pcall(vehicle.updatePhysicsNetwork, vehicle)
    return true
end

function EnclosureChallenge.reboundVehicle(pl, x, y, z)
    pl = pl or getPlayer()
    local vehicle = pl and pl:getVehicle() or nil
    if not vehicle or EnclosureChallenge.getVehicleSeat(pl, vehicle) ~= 0 then return false end
    if isClient() then
        local moved = EnclosureChallenge.reboundMoveVehicle(vehicle, tonumber(x), tonumber(y))
        if not moved then return false end
        sendClientCommand("EnclosureChallenge", "reboundVehicle", { id = vehicle:getId(), x = tonumber(x), y = tonumber(y), z = tonumber(z or vehicle:getZ()) })
        return moved
    end
    return EnclosureChallenge.reboundMoveVehicle(vehicle, tonumber(x), tonumber(y))
end


function EnclosureChallenge.getCar()
	local pl = getPlayer();
	local car = nil;
	if pl:getVehicle() then
		car = pl:getVehicle();
	end
	return car
end

function EnclosureChallenge.carHandler(pl)
	if not EnclosureChallenge.isChallenger() then return end
	local car = EnclosureChallenge.getCar()
	if car then
        if  SandboxVars.EnclosureChallenge.LeakBattery then
            local item = car:getPartById("Battery")
            if item then
                local batt = item:getInventoryItem()
                if batt and batt:getUsedDelta() ~= 0 then
                    batt:setUsedDelta(0)
                end
            end
        end
        if SandboxVars.EnclosureChallenge.StopCar then
            if car:isEngineRunning() then
                ISVehicleMenu.onShutOff(pl)
            end
		end
	end
end
Events.OnEnterVehicle.Add(EnclosureChallenge.carHandler)

function EnclosureChallenge.forceExitCar(pl)
    pl = pl or getPlayer()
	if not pl then return end
	local car = pl:getVehicle()
	if not car then return end
	local seat = car:getSeat(pl)
	car:exit(pl)
	if seat and seat >= 0 then
		car:setCharacterPosition(pl, seat, "outside")
		if car.transmitCharacterPosition then car:transmitCharacterPosition(seat, "outside") end
	end
	pl:PlayAnim("Idle")
	triggerEvent("OnExitVehicle", pl)
    car:updateHasExtendOffsetForExitEnd(pl)
end
